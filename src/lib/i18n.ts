export const DICT: Record<Lang, Dict> = { pt, en };
export type { Dict };

export const LangCtx = createContext<{ lang: Lang; t: Dict; setLang: (l: Lang) => void }>({
  lang: 'pt',
  t: pt,
  setLang: () => {},
});
export const useT = () => useContext(LangCtx);

export function initialLang(): Lang {
  try {
    const saved = localStorage.getItem('a2-lang');
    if (saved === 'pt' || saved === 'en') return saved;
  } catch {
    /* sem storage */
  }
  return typeof navigator !== 'undefined' && navigator.language && !navigator.language.startsWith('pt') ? 'en' : 'pt';
}
export const sizeLabel = (lang: Lang, z: string) => (lang === 'en' ? ({ P: 'S', M: 'M', G: 'L' } as Record<string, string>)[z] : z);
